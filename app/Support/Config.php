<?php

declare(strict_types=1);

namespace Argus\Support;

/**
 * Access to config/config.php, written by the installer.
 */
final class Config
{
    private static ?array $data = null;

    public static function path(): string
    {
        return BASE_PATH . '/config/config.php';
    }

    public static function samplePath(): string
    {
        return BASE_PATH . '/config/config.sample.php';
    }

    public static function installed(): bool
    {
        return is_file(self::path());
    }

    public static function load(): void
    {
        if (self::$data !== null) {
            return;
        }

        if (self::installed()) {
            /** @var array $config */
            $config = require self::path();
            self::$data = is_array($config) ? $config : [];
        } else {
            self::$data = [];
        }
    }

    /** Dot-notation lookup: Config::get('db.host'). */
    public static function get(string $key, mixed $default = null): mixed
    {
        self::load();

        $segments = explode('.', $key);
        $value = self::$data;

        foreach ($segments as $segment) {
            if (!is_array($value) || !array_key_exists($segment, $value)) {
                return $default;
            }
            $value = $value[$segment];
        }

        return $value;
    }

    public static function appName(): string
    {
        $name = trim((string) self::get('app.name', 'Argus'));

        return $name !== '' ? $name : 'Argus';
    }

    /** Write a complete config file with restrictive permissions. */
    public static function write(array $config): void
    {
        $dir = BASE_PATH . '/config';
        if (!is_dir($dir) && !mkdir($dir, 0750, true) && !is_dir($dir)) {
            throw new \RuntimeException('Unable to create the config directory.');
        }

        $php = "<?php\n\n/**\n * Generated by the Argus installer on "
            . gmdate('Y-m-d H:i:s') . " UTC.\n * Keep this file private: it holds database and encryption secrets.\n */\n\nreturn "
            . var_export($config, true) . ";\n";

        $target = self::path();
        if (file_put_contents($target, $php, LOCK_EX) === false) {
            throw new \RuntimeException('Unable to write config/config.php. Check directory permissions.');
        }

        @chmod($target, 0640);
        self::$data = $config;
    }

    /** True when the browser/session may be shown the setup wizard. */
    public static function needsSetup(): bool
    {
        return !self::installed();
    }
}
